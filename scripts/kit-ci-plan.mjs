#!/usr/bin/env node
// Lists a kit's CI test jobs for .github/workflows/kit-ci.yml: one job per test script (`test` and
// `test:*`) of each package folder that has a pnpm lockfile, `web/` and the repository root.
//
//   node scripts/kit-ci-plan.mjs <kit checkout> [--github-output]
//
// Skipped: `test:ci` and `test:ci:full` (a kit's own all-in-one runners) and any script that only
// chains other scripts (`pnpm a && pnpm b`), whose parts are jobs of their own. A web script's job
// is named after the script; a root script's job is `root/<script>`.
//
// The kit may add `.github/kit-ci.json`: `exclude` (job names that cannot run on a hosted runner)
// and `maxParallel` (test jobs at once; default 6, which keeps one kit's run at 8 jobs with
// build and rust). With --github-output the result is printed as `matrix=`, `max_parallel=` and
// `xtask=` lines for $GITHUB_OUTPUT; without it, as JSON.
//
// Text-only path. With `--base <commit>` (the merge base with the kit's main; the workflow gives
// none for nightly and hand-started runs, which always test everything) it also prints
// `text_only=true|false`: true only when every file changed from <base> to `--head` (default
// HEAD) is on the text-only list below, and the change is not empty. Such a run skips the build,
// Rust and test jobs; its `Text only` job runs
//
//   node scripts/kit-ci-plan.mjs <kit checkout> --check-text --base <commit> [--head <commit>]
//
// which checks that the changed files are UTF-8 text and that `git diff --check` finds nothing
// (conflict markers, trailing whitespace). `--summary <file>` appends a Markdown summary.
import { spawnSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const SKIP = new Set(['test:ci', 'test:ci:full'])
const CHAIN = /^\s*pnpm(?:\s+-s)?(?:\s+run)?\s+[\w:.-]+(?:\s*&&\s*pnpm(?:\s+-s)?(?:\s+run)?\s+[\w:.-]+)*\s*$/
const DEFAULT_MAX_PARALLEL = 6

const readJson = (file) => JSON.parse(fs.readFileSync(file, 'utf8'))

export function planKit(repo) {
  const configFile = path.join(repo, '.github', 'kit-ci.json')
  const config = fs.existsSync(configFile) ? readJson(configFile) : {}
  const exclude = new Set(config.exclude ?? [])
  const include = []
  const seen = new Set()
  for (const dir of ['.', 'web']) {
    const folder = path.join(repo, dir)
    if (!fs.existsSync(path.join(folder, 'package.json')) || !fs.existsSync(path.join(folder, 'pnpm-lock.yaml'))) continue
    const scripts = readJson(path.join(folder, 'package.json')).scripts ?? {}
    for (const [script, command] of Object.entries(scripts)) {
      if (script !== 'test' && !script.startsWith('test:')) continue
      if (SKIP.has(script) || CHAIN.test(command)) continue
      const name = dir === '.' ? `root/${script}` : script
      seen.add(name)
      if (exclude.has(name)) continue
      include.push({ dir, script, name, slug: name.replace(/[^\w.-]+/g, '-') })
    }
  }
  const unknown = [...exclude].filter((name) => !seen.has(name))
  if (unknown.length) throw new Error(`.github/kit-ci.json excludes jobs that do not exist: ${unknown.join(', ')}`)
  return {
    include,
    maxParallel: config.maxParallel ?? DEFAULT_MAX_PARALLEL,
    xtask: fs.existsSync(path.join(repo, 'tools', 'xtask')),
  }
}

// The text-only list: the only files whose change may skip a kit's build and tests. Everything
// else (source, config, data, workflows, features.yaml, cases/, kit.json, images, binaries) takes
// the full run. Markdown counts only where no build or test of a kit reads it: at the root, directly
// in .github/, and under docs/ outside the folders below. Markdown elsewhere is read by builds and
// tests (checked across the 16 kits, 2026-11): crate and vendored-crate READMEs compiled into the
// docs and doctests (`#![doc = include_str!("../README.md")]`), agent/guide.md (included by tests;
// check-manifest wants it), conformance/*.md and test fixtures, samples and corpora;
// under docs/: attribution.md (the asset checks of `cargo xtask ci` and web specs),
// parity/ (generated and checked by xtask parity), features/ (included by tests and
// regenerated by stale-checks).
const TEXT_ONLY_FILES = new Set(['.github/CODEOWNERS'])
const TEXT_ONLY_TREES = ['.claude/', '.github/ISSUE_TEMPLATE/']
const ROOT_LEGAL = /^(LICENSE|NOTICE)([.-][\w.-]+)?$/
const DOCS_EXCLUDED_FILES = new Set(['docs/attribution.md'])
const DOCS_EXCLUDED_FOLDERS = new Set([
  'parity', 'features', 'generated',
  'cases', 'conformance', 'expected', 'fixtures', 'fixture', 'tests', 'test', '__tests__', 'testdata', 'test-data',
  'e2e', 'samples', 'sample', 'corpus', 'examples', 'golden', 'snapshots', 'data', 'assets', 'public', 'src', 'agent',
])
// Regular files only (no symlink 120000, no submodule 160000); 000000 is the missing side of an
// added or deleted file.
const TEXT_ONLY_MODES = new Set(['000000', '100644', '100755'])
const TEXT_ONLY_STATUSES = new Set(['A', 'M', 'D', 'R'])

export const TEXT_ONLY_SENTENCE = 'text-only change: full checks skipped (kit-ci text-only path)'

/** Whether a changed repository path (relative, `/`-separated) is on the text-only list. */
export function isTextOnlyPath(file) {
  const parts = file.split('/')
  if (parts.some((part) => part === '' || part === '.' || part === '..')) return false
  if (TEXT_ONLY_FILES.has(file) || TEXT_ONLY_TREES.some((tree) => file.startsWith(tree))) return true
  const name = parts.at(-1)
  if (parts.length === 1) return name.endsWith('.md') || ROOT_LEGAL.test(name)
  if (!name.endsWith('.md')) return false
  if (parts.length === 2 && parts[0] === '.github') return true
  if (parts[0] !== 'docs' || DOCS_EXCLUDED_FILES.has(file)) return false
  return !parts.slice(1, -1).some((folder) => DOCS_EXCLUDED_FOLDERS.has(folder))
}

/**
 * Whether a change is text-only. `changes` are `{ status, path, oldPath?, oldMode?, newMode? }`
 * as `git diff --raw` reports them (status A, M, D, R, T, ...). An empty change is not text-only,
 * so a run of an unchanged main still tests everything.
 */
export function classifyChanges(changes) {
  if (!changes.length) return { textOnly: false, reason: 'nothing changed against main' }
  for (const change of changes) {
    const paths = [change.oldPath, change.path].filter(Boolean)
    if (!TEXT_ONLY_STATUSES.has(change.status)) return { textOnly: false, reason: `${change.path}: change of kind ${change.status}` }
    for (const mode of [change.oldMode, change.newMode]) {
      if (mode !== undefined && !TEXT_ONLY_MODES.has(mode)) return { textOnly: false, reason: `${change.path}: mode ${mode} (not a regular file)` }
    }
    const outside = paths.find((file) => !isTextOnlyPath(file))
    if (outside) return { textOnly: false, reason: `${outside} is not on the text-only list` }
  }
  return { textOnly: true, reason: `${changes.length} changed file(s), all on the text-only list` }
}

function git(repo, args, options = {}) {
  const result = spawnSync(process.env.GIT || 'git', ['-C', repo, ...args], { maxBuffer: 256 * 1024 * 1024, ...options })
  if (result.error) throw result.error
  return result
}

/** The files changed from `base` to `head`, each side of a rename as its own entry. */
export function changesBetween(repo, base, head = 'HEAD') {
  const result = git(repo, ['diff', '--raw', '-z', '--no-renames', '--no-abbrev', '--no-ext-diff', base, head])
  if (result.status !== 0) throw new Error(`git diff ${base} ${head}: ${result.stderr.toString().trim()}`)
  const fields = result.stdout.toString('utf8').split('\0')
  const changes = []
  for (let index = 0; index + 1 < fields.length; index += 2) {
    const [oldMode, newMode, , , status] = fields[index].replace(/^:/, '').split(' ')
    changes.push({ status: status[0], path: fields[index + 1], oldMode, newMode })
  }
  return changes
}

const describe = (change) => `${change.status} ${change.path}`

/** The `Text only` job's checks: still text-only, UTF-8 text without NUL bytes, `git diff --check`. */
export function checkText(repo, base, head = 'HEAD') {
  const changes = changesBetween(repo, base, head)
  const problems = []
  const verdict = classifyChanges(changes)
  if (!verdict.textOnly) problems.push(`not a text-only change: ${verdict.reason}`)
  const utf8 = new TextDecoder('utf-8', { fatal: true })
  for (const change of changes.filter((entry) => entry.status !== 'D')) {
    const blob = git(repo, ['cat-file', 'blob', `${head}:${change.path}`])
    if (blob.status !== 0) {
      problems.push(`${change.path}: cannot read it at ${head}`)
      continue
    }
    try {
      utf8.decode(blob.stdout)
      if (blob.stdout.includes(0)) problems.push(`${change.path}: contains NUL bytes (not text)`)
    } catch {
      problems.push(`${change.path}: not UTF-8 text`)
    }
  }
  const check = git(repo, ['diff', '--check', '--no-ext-diff', base, head])
  if (check.status !== 0) {
    const out = `${check.stdout}${check.stderr}`.trim()
    problems.push(`git diff --check found whitespace errors or conflict markers:\n${out}`)
  }
  return { changes, problems }
}

function parseArgs(argv) {
  const options = { repo: undefined, githubOutput: false, checkText: false, base: undefined, head: 'HEAD', summary: undefined }
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index]
    if (arg === '--github-output') options.githubOutput = true
    else if (arg === '--check-text') options.checkText = true
    else if (arg === '--base' || arg === '--head' || arg === '--summary') {
      const value = argv[++index]
      if (!value) throw new Error(`${arg} needs a value`)
      options[arg.slice(2)] = value
    } else if (!arg.startsWith('--') && options.repo === undefined) options.repo = arg
    else throw new Error(`unknown argument ${arg}`)
  }
  if (!options.repo) throw new Error('no kit checkout given')
  if (options.checkText && !options.base) throw new Error('--check-text needs --base')
  return options
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  let options
  try {
    options = parseArgs(process.argv.slice(2))
  } catch (error) {
    console.error(`${error.message}\nusage: node scripts/kit-ci-plan.mjs <kit checkout> [--github-output] [--base <commit> [--head <commit>]] [--summary <file>]\n       node scripts/kit-ci-plan.mjs <kit checkout> --check-text --base <commit> [--head <commit>] [--summary <file>]`)
    process.exit(2)
  }
  const repo = path.resolve(options.repo)
  const summarize = (text) => options.summary && fs.appendFileSync(options.summary, `${text}\n`)
  try {
    if (options.checkText) {
      const { changes, problems } = checkText(repo, options.base, options.head)
      console.log(`changed files (${options.base.slice(0, 12)}..${options.head.slice(0, 12)}):`)
      for (const change of changes) console.log(`  ${describe(change)}`)
      const list = changes.map((change) => `- \`${describe(change)}\``).join('\n')
      if (problems.length) {
        for (const problem of problems) console.error(`error: ${problem}`)
        summarize(`### Text-only change: the text checks failed\n\n${problems.map((problem) => `- ${problem.replaceAll('\n', '\n  ')}`).join('\n')}\n\nChanged files:\n\n${list}`)
        process.exit(1)
      }
      console.log(TEXT_ONLY_SENTENCE)
      summarize(`### ${TEXT_ONLY_SENTENCE}\n\nEvery changed file is on the text-only list of \`scripts/kit-ci-plan.mjs\` in KitionAI/kition, so the build, Rust and test jobs were skipped; the files are UTF-8 text and \`git diff --check\` is clean. \`scripts/kit-ci.sh push <kit> --full\` forces the full run.\n\nChanged files:\n\n${list}`)
    } else {
      const plan = planKit(repo)
      let verdict = { textOnly: false, reason: 'no base commit (nightly, started by hand, or no merge base with main)' }
      if (options.base) {
        try {
          verdict = classifyChanges(changesBetween(repo, options.base, options.head))
        } catch (error) {
          verdict = { textOnly: false, reason: `cannot list the changes (${error.message})` }
        }
      }
      if (options.githubOutput) {
        console.log(`matrix=${JSON.stringify({ include: plan.include })}`)
        console.log(`max_parallel=${plan.maxParallel}`)
        console.log(`xtask=${plan.xtask}`)
        console.log(`text_only=${verdict.textOnly}`)
      } else {
        console.log(JSON.stringify({ ...plan, textOnly: verdict.textOnly }, null, 2))
      }
      console.error(`${verdict.textOnly ? 'text-only run' : 'full run'}: ${verdict.reason}`)
      summarize(verdict.textOnly ? `Text-only change (${verdict.reason}): the build, Rust and test jobs are skipped.` : `Full run: ${verdict.reason}.`)
    }
  } catch (error) {
    console.error(error.message)
    process.exit(1)
  }
}
